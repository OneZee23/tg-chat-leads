/**
 * Персонализированное первое сообщение.
 *
 * Идея из обратной связи и из собственных цифр: простыня на полстраницы,
 * одинаковая для всех, даёт ~1% ответов. Короткая первая строка про
 * конкретный предмет человека цепляет заметно лучше — и, что важнее, реже
 * воспринимается как спам, потому что выглядит по делу.
 *
 * Предмет достаётся из текста объявления, а НЕ из matched_keywords: там в
 * `job:` лежит общее слово («репетитор», «педагог»), которое сработало
 * первым, а не предмет. Поэтому сканируем текст отдельно.
 *
 * Тон намеренно мягкий: вопрос, а не оффер, и явное «без обид» в конце —
 * получатель ничего не должен и легко может не ответить.
 */

/**
 * Стем предмета → как он звучит в «набираете учеников по ___».
 * Порядок = приоритет: специальные предметы раньше, чтобы «русский как
 * иностранный» не проиграл общему «русский».
 */
const SUBJECT_LABELS: Array<[string, string]> = [
  ['русский как иностранн', 'русскому как иностранному'],
  ['английск', 'английскому'],
  ['немецк', 'немецкому'],
  ['французск', 'французскому'],
  ['испанск', 'испанскому'],
  ['итальянск', 'итальянскому'],
  ['китайск', 'китайскому'],
  ['турецк', 'турецкому'],
  ['арабск', 'арабскому'],
  ['корейск', 'корейскому'],
  ['японск', 'японскому'],
  ['узбекск', 'узбекскому'],
  ['математик', 'математике'],
  ['физик', 'физике'],
  ['хими', 'химии'],
  ['биолог', 'биологии'],
  ['информатик', 'информатике'],
  ['программирован', 'программированию'],
  ['обществознан', 'обществознанию'],
  ['истори', 'истории'],
  ['географ', 'географии'],
  ['русск', 'русскому языку'],
  ['литератур', 'литературе'],
  ['вокал', 'вокалу'],
  ['сольфеджио', 'сольфеджио'],
  ['фортепиано', 'фортепиано'],
  ['пианино', 'фортепиано'],
  ['гитар', 'гитаре'],
  ['скрипк', 'скрипке'],
  ['йог', 'йоге'],
  ['пилатес', 'пилатесу'],
  ['фитнес', 'фитнесу'],
  ['танц', 'танцам'],
  ['рисован', 'рисованию'],
  ['живопис', 'живописи'],
  ['шахмат', 'шахматам'],
  ['логопед', 'логопедии'],
];

export function detectSubject(sampleText: string | null): string | null {
  if (!sampleText) return null;
  const text = sampleText.toLowerCase().replace(/ё/g, 'е');

  for (const [stem, label] of SUBJECT_LABELS) {
    if (text.includes(stem)) return label;
  }
  return null;
}

/**
 * Первая строка. С предметом — прицельный вопрос, без — мягкий общий.
 * Всегда вопрос: он возвращает разговор человеку и на него легко ответить.
 */
export function buildHook(sampleText: string | null): string {
  const subject = detectSubject(sampleText);
  return subject
    ? `Здравствуйте! Увидел ваше объявление — набираете учеников по ${subject}?`
    : 'Здравствуйте! Увидел ваше объявление — вы сейчас набираете учеников?';
}

/**
 * Полное сообщение: хук + тело. Тело редактируется в файле, чтобы менять
 * текст без пересборки; хук подставляется под каждого.
 */
export function buildOutreachMessage(sampleText: string | null, body: string): string {
  return `${buildHook(sampleText)}\n\n${body.trim()}`;
}

