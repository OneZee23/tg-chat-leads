/**
 * Порядок очереди холодной рассылки.
 *
 * `score` из детектора — это гейт «объявление или нет», а не ранжирование.
 * На корпусе из 955 разосланных объявлений у 630 (66%) он равен максимуму 6:
 * внутри очереди он почти ничего не различает, и реальный порядок задавал
 * вторичный ключ `last_seen_at`.
 *
 * Вторым ключом идёт поведенческий признак — сколько раз сканер видел
 * объявление от этого человека. На вручную размеченных ответах он делит
 * выборку резко: у публиковавших до пяти раз доля содержательного интереса
 * 0.66, у публиковавших шесть и больше — 0.33 (Fisher p = 0.008, знак
 * устойчив на 4000 бутстрэпах, эффект держится внутри страты score = 6).
 *
 * Почему именно он: все четверо ответивших «у меня нет учеников» и шестеро
 * из семи «у меня уже своя система» оказались в группе от шести объявлений.
 * Один признак ловит оба класса брака сразу — и пустого новичка, которому
 * нечего учитывать, и ветерана, уже решившего задачу.
 *
 * ЧЕГО ЗДЕСЬ НЕТ: текстовых признаков «состоявшейся практики». Гипотеза
 * проверена и опровергнута — упоминания стажа и результатов отвечают ХУЖЕ
 * базы (lift 0.79-0.86), а признаки новичка ЛУЧШЕ (1.34-1.62). Причина
 * структурная: полностью загруженный преподаватель объявление не даёт
 * вообще, и в корпусе из объявлений его нет по построению.
 *
 * Величина весов НЕ откалибрована и калибровке не поддаётся: при сортировке
 * кортежем значение имеет только знак и порядок, что и измерено. Поэтому
 * кортеж, а не сумма со `score` — сложение позволило бы пятёрке обогнать
 * шестёрку, а такого измерения нет.
 *
 * Измерение целиком: docs/2026-09-04-lead-scoring-measurement.md
 */
export function leadQueueScoreSql(alias?: string): string {
  const col = alias ? `"${alias}"."ad_messages_count"` : 'ad_messages_count';
  return (
    `(CASE WHEN ${col} <= 5 THEN 2 ELSE 0 END)` +
    ` + (CASE WHEN ${col} >= 30 THEN -1 ELSE 0 END)`
  );
}
