// ─────────────────────────────────────────────────────────────────────────
//  Авто-ответ по шаблону
// ─────────────────────────────────────────────────────────────────────────
//
// Отвечаем шаблоном ТОЛЬКО на однозначные случаи:
//  • явный позитив/обещание попробовать → «рад, что заинтересовало»;
//  • явный отказ → «спасибо, что ответили».
// Вопрос и нейтральное (просто «здравствуйте», «я посредник…») отдаём
// человеку: шаблон на них либо соврёт, либо прозвучит невпопад.
//
// Тексты — ровно те, которыми OneZee отвечал руками, дословно.

const AUTO_POSITIVE =
  'Супер, рад что заинтересовало)\n\n' +
  'Если будут вопросы или возможно найдете какие-то недочеты, пишите, исправлю быстро';

const AUTO_DECLINE = 'Спасибо, что в любом случае ответили :)';

export interface AutoReply {
  kind: ReplyKind;
  /** Текст авто-ответа или null, если случай надо разобрать руками. */
  text: string | null;
}

export function autoReplyTemplate(text: string): AutoReply {
  const kind = classifyReply(text);
  switch (kind) {
    case 'positive':
      return { kind, text: AUTO_POSITIVE };
    case 'decline':
      return { kind, text: AUTO_DECLINE };
    // question и neutral — только руками.
    default:
      return { kind, text: null };
  }
}

// ─────────────────────────────────────────────────────────────────────────
//  Полное авто-решение по ответу: ответить / закрыть / отдать человеку
// ─────────────────────────────────────────────────────────────────────────

export type AutoAction = 'send' | 'clear' | 'manual';

export interface AutoDecision {
  action: AutoAction;
  /** Текст для action='send'. */
  text: string | null;
  kind: ReplyKind;
  /** Почему такое решение — для превью. */
  reason: string;
}

/** Просит ссылку / гайд / «как завести» — нужен онбординг, а не шаблон. */
const REQUEST_MARKERS = [
  'киньте',
  'скинь',
  'пришлите',
  'дайте ссылк',
  'ссылку',
  'гайд',
  'как туда',
  'как добавить',
  'как завести',
  'как начать',
  'как регать',
  'как зарегистр',
  'как попасть',
  'как пользоваться',
];

/** Развёрнутый фидбек — заслуживает личного ответа, не шаблона. */
const FEEDBACK_MARKERS = [
  'докрутить',
  'не хватает',
  'было бы',
  'предлож',
  'фидбек',
  'недочет',
  'улучшить',
  'пожелани',
  'вкладку',
  'функци',
  'фичу',
  'добавьте',
];

// Длиннее этого — почти всегда осмысленное сообщение, а не «ок/спасибо».
const SUBSTANTIVE_LEN = 200;

// «Закрыть без ответа» только для КОРОТКИХ нейтральных («Хорошо», «Спасибо
// большое», «Да набираю»). Всё длиннее — глазами: там может быть активный
// юзер, баг-репорт или предложение отзыва, которых нельзя молча закрывать.
const NEUTRAL_CLEAR_MAXLEN = 30;

/**
 * Что делать с ответом человека без твоего участия:
 *  • manual — оставить тебе (вопрос / просьба о ссылке / развёрнутый фидбек);
 *  • send   — отправить шаблон (позитив/отказ) и закрыть;
 *  • clear  — короткое нейтральное («ок», «спасибо»): ответа не требует,
 *             просто убираем из списка.
 */
export function autoReplyDecision(text: string): AutoDecision {
  const normalized = (text ?? '').toLowerCase().replace(/ё/g, 'е');
  const kind = classifyReply(text);

  if (kind === 'question') {
    return { action: 'manual', text: null, kind, reason: 'вопрос — нужен твой ответ' };
  }
  if (REQUEST_MARKERS.some((m) => normalized.includes(m))) {
    return {
      action: 'manual',
      text: null,
      kind,
      reason: 'просит ссылку/гайд — ответь с онбордингом',
    };
  }
  if (
    normalized.length > SUBSTANTIVE_LEN ||
    FEEDBACK_MARKERS.some((m) => normalized.includes(m))
  ) {
    return {
      action: 'manual',
      text: null,
      kind,
      reason: 'развёрнутый ответ/фидбек — ответь лично',
    };
  }
  if (kind === 'decline') {
    return { action: 'send', text: AUTO_DECLINE, kind, reason: 'отказ' };
  }
  if (kind === 'positive') {
    return { action: 'send', text: AUTO_POSITIVE, kind, reason: 'позитив' };
  }
  // Нейтральное. Короткое «ок/спасибо» — закрыть. Длиннее — тебе: там может
  // быть активный юзер, баг или предложение отзыва.
  if (normalized.length <= NEUTRAL_CLEAR_MAXLEN) {
    return {
      action: 'clear',
      text: null,
      kind,
      reason: 'короткое «ок/спасибо» — ответа не требует',
    };
  }
  return {
    action: 'manual',
    text: null,
    kind,
    reason: 'содержательное нейтральное — глянь сам',
  };
}
