/**
 * Разбор ответа человека и заготовка реплики.
 *
 * Задача — не написать финальный текст за тебя, а рассортировать входящие:
 * на явный отказ и тёплое «хочу попробовать» заготовка годится как есть,
 * а вопрос отдаём тебе с пометкой — на вопрос про конкретную фичу шаблон
 * ответит неверно (можно случайно пообещать то, чего нет), поэтому такие
 * пишутся руками.
 */

export type ReplyKind = 'decline' | 'question' | 'positive' | 'neutral';

export interface ReplySuggestion {
  kind: ReplyKind;
  /** Готовый черновик или null, если нужен ручной ответ. */
  draft: string | null;
  /** Что делать дальше, одной строкой. */
  hint: string;
}

const DECLINE_MARKERS = [
  'не интересует',
  'не интересно',
  'неинтересно',
  'неудобно',
  'спасибо, нет',
  'нет, спасибо',
  'не нужно',
  'не надо',
  'не актуально',
  'не подходит',
  'уже есть',
  'не пользуюсь',
];

/**
 * Отрицание перед позитивным словом: «не хочу», «не очень интересно»,
 * «не буду пробовать». Без этого «не хочу» ловилось как позитив, потому что
 * содержит «хочу». Допускаем до двух слов между «не» и корнем.
 *
 * Граница слова руками через `(^|[^а-я])`, а НЕ через `\b`: `\b` в JS
 * работает по ASCII и с кириллицей молча не срабатывает (текст уже
 * нормализован — нижний регистр, ё→е).
 */
const DECLINE_NEGATION =
  /(^|[^а-я])не(\s+\S+){0,2}\s+(хоч|интерес|удобн|нужн|подход|буд|готов|проб|пойд|стан|восполь|протест|ознаком)/;

/**
 * Сильная похвала продукту. Если она стоит рядом с фразой-отказом, отказ,
 * скорее всего, относится к детали, а не к сервису («супер, всё удобно, НЕ
 * НУЖНО разбираться»), — такой случай двусмысленный и уходит на ручной
 * разбор, а не режется в decline. Слова подобраны так, чтобы не задевать
 * отрицания: «удобн» сюда НЕ входит (иначе поймало бы «неудобно»).
 */
const STRONG_PRAISE = [
  'супер',
  'класс', // классно / классный
  'отличн',
  'лаконичн',
  'качествен',
  'понрав',
  'здорово',
  'красив',
  'нравится',
];

const POSITIVE_MARKERS = [
  'хочу',
  'давайте',
  // Два стема глагола «попробовать»: «пробу» (попробую/опробую/пробую) и
  // «пробов» (попробовать/попробовала). Голый «проб» брать нельзя — заденет
  // «проблема».
  'пробу',
  'пробов',
  'отлично',
  'удобно',
  'круто',
  'прикольно',
  'интересно',
  'посмотрю',
  'гляну',
  'зарегистрир',
  'супер',
  // Обещание воспользоваться/протестировать — тоже интерес.
  'воспольз',
  'протестир',
  'потестир',
  'ознаком',
];
// «спасибо» намеренно НЕ здесь: голое «спасибо большое» — вежливость, а не
// интерес, и слать на него «рад что заинтересовало» звучит как недочитавший
// бот. «Спасибо, попробую» остаётся позитивом через «попробу».

// Черновики для ручного разбора (yarn replies). Тон — как OneZee пишет сам:
// тепло, разговорно, «рад что заинтересовало», «поправлю быстро», без
// канцелярита вроде «Ссылка — …, вход по почте».

const ONBOARDING = `Супер, рад что заинтересовало) Заходите на teachtrack.ru — всё бесплатно. Учеников можно завести сразу списком, хоть из Excel, хоть просто текстом, и самим им регистрироваться не нужно. Что-то не сойдётся или не хватит — пишите, помогу и поправлю быстро)`;

const SOFT = `Спасибо, что ответили) Если захотите глянуть — сервис тут, teachtrack.ru, бесплатно. Что-то будет не так или не хватит — пишите, поправлю быстро)`;

const DECLINE = `Спасибо, что в любом случае ответили) Если вдруг пригодится позже — teachtrack.ru всегда на месте. Удачи с учениками!`;

export function classifyReply(text: string): ReplyKind {
  const normalized = (text ?? '').toLowerCase().replace(/ё/g, 'е');
  if (normalized.trim().length === 0) return 'neutral';

  // Вопрос проверяем ПЕРВЫМ. Раньше он шёл после отказа, и тёплое, но
  // содержащее фразу-отказ сообщение с вопросом уходило в decline:
  // «сейчас ищу такую платформу, попробую, но если уже не актуально?» →
  // ловилось «не актуально» и человек получал холодный отказ вместо ответа
  // на вопрос. Раз человек спрашивает — это к тебе руками, всегда.
  if (normalized.includes('?')) return 'question';

  // Отказ: явные фразы + отрицание позитива («не хочу», «не буду пробовать»).
  // «спасибо, не интересует» содержит и «спасибо» (позитив), но по сути нет.
  const declineHit =
    DECLINE_MARKERS.some((m) => normalized.includes(m)) ||
    DECLINE_NEGATION.test(normalized);
  if (declineHit) {
    // Отказ-фраза рядом с сильной похвалой — двусмысленно («супер, удобно, не
    // нужно разбираться»). Не режем в отказ, отдаём человеку.
    if (STRONG_PRAISE.some((p) => normalized.includes(p))) return 'neutral';
    return 'decline';
  }

  if (POSITIVE_MARKERS.some((m) => normalized.includes(m))) return 'positive';

  return 'neutral';
}

export function suggestReply(text: string): ReplySuggestion {
  const kind = classifyReply(text);

  switch (kind) {
    case 'decline':
      return {
        kind,
        draft: DECLINE,
        hint: 'вежливый отказ — ответь и пометь: yarn skip',
      };
    case 'question':
      return {
        kind,
        draft: null,
        hint: 'вопрос — ответь сам, шаблон соврёт (может пообещать несуществующее)',
      };
    case 'positive':
      return { kind, draft: ONBOARDING, hint: 'тёплый — веди в онбординг' };
    default:
      return { kind, draft: SOFT, hint: 'нейтральный — лёгкое касание' };
  }
}

